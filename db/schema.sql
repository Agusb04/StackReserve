-- Esquema relacional de referencia para la migración futura a JPA.
-- La implementación actual del backend mantiene persistencia en memoria.
-- Cada clave foránea y restricción está trazada en db/modelo-er.md.

create table sala (
    id_sala bigint generated by default as identity primary key,
    codigo varchar(32) not null,
    nombre varchar(120) not null,
    capacidad_maxima integer not null,
    constraint uk_sala_codigo unique (codigo),
    constraint ck_sala_capacidad check (capacidad_maxima > 0)
);

create table turno (
    id_turno bigint generated by default as identity primary key,
    id_sala bigint not null,
    fecha date not null,
    hora_inicio time not null,
    hora_fin time not null,
    constraint fk_turno_sala foreign key (id_sala) references sala (id_sala),
    constraint ck_turno_horario check (hora_inicio < hora_fin)
);

create table estudiante (
    legajo varchar(32) primary key,
    nombre varchar(120) not null,
    estado_habilitacion varchar(32) not null,
    constraint ck_estudiante_estado
        check (estado_habilitacion in ('ACTIVO', 'SUSPENDIDO'))
);

create table personal (
    legajo varchar(32) primary key,
    nombre varchar(120) not null
);

create table reserva (
    id_reserva varchar(16) primary key,
    legajo_estudiante varchar(32) not null,
    id_turno bigint not null,
    fecha_creacion timestamp not null,
    constraint fk_reserva_estudiante foreign key (legajo_estudiante)
        references estudiante (legajo),
    constraint fk_reserva_turno foreign key (id_turno) references turno (id_turno)
);

create table historial_estado (
    id_historial bigint generated by default as identity primary key,
    id_reserva varchar(16) not null,
    legajo_personal varchar(32),
    fecha_registro timestamp not null,
    estado varchar(32) not null,
    constraint fk_historial_reserva foreign key (id_reserva)
        references reserva (id_reserva),
    constraint fk_historial_personal foreign key (legajo_personal)
        references personal (legajo),
    constraint ck_historial_estado
        check (estado in ('confirmada', 'presente', 'ausente', 'cancelada'))
);

create index idx_turno_sala_fecha on turno (id_sala, fecha);
create index idx_reserva_estudiante on reserva (legajo_estudiante);
create index idx_historial_reserva on historial_estado (id_reserva);
